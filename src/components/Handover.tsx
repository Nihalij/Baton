"use client";

import { useMemo, useState } from "react";
import { useStore } from "@/lib/store";
import { PEOPLE, CLUB } from "@/lib/data";
import { fmtDate, nextActions, redact, viewFor } from "@/lib/pipeline";
import type { Chunk, Claim, ClaimType, Person } from "@/lib/types";
import { Button, Card, ClaimRow, Hint, cx } from "./ui";

const SECTIONS: { title: string; types: ClaimType[]; empty?: string }[] = [
  { title: "Ownership and role changes", types: ["handover", "owner", "task"] },
  { title: "Decisions and why they were made", types: ["decision", "techchoice"] },
  { title: "Deadlines", types: ["deadline"] },
  { title: "Risks, blockers and requirements", types: ["risk", "dependency"] },
  { title: "Recurring problems and known fixes", types: ["recurring"] },
  { title: "Contacts and access", types: ["contact", "credential"] },
  { title: "Finance", types: ["finance"] },
];

function dedupe(claims: Claim[]) {
  const seen = new Set<string>();
  return claims.filter((c) => {
    if (c.type !== "deadline" || !c.attribute) return true;
    const k = `${c.attribute}|${c.value}`;
    if (seen.has(k)) return false;
    seen.add(k);
    return true;
  });
}

function toMarkdown(person: Person, version: number, claims: Claim[], chunkMap: Map<string, Chunk>) {
  const lines = [`# Handover for ${person.name} (${person.title})`, "", `${CLUB.name} · version ${version} · generated by Baton`, ""];
  for (const sec of SECTIONS) {
    const list = claims.filter((c) => sec.types.includes(c.type));
    if (!list.length) continue;
    lines.push(`## ${sec.title}`, "");
    for (const c of list) {
      const src = c.evidence.map((e) => chunkMap.get(e.chunkId)).filter(Boolean).map((ch) => `${ch!.sourceName} › ${ch!.title}`);
      lines.push(`- [${c.status}] ${redact(c.text)}  \n  _Source: ${[...new Set(src)].join("; ")}_`);
    }
    lines.push("");
  }
  const gaps = claims.filter((c) => c.type === "gap" && !c.answeredBy);
  if (gaps.length) {
    lines.push("## Open gaps", "", ...gaps.map((g) => `- ${g.text}`), "");
  }
  return lines.join("\n");
}

export function Handover() {
  const { s, setReader, acknowledge, flag, setStep } = useStore();
  const [flagging, setFlagging] = useState<string | null>(null);
  const [reason, setReason] = useState("");
  const chunkMap = useMemo(() => new Map(s.chunks.map((c) => [c.id, c])), [s.chunks]);
  const latest = s.versions[0];
  const readers = PEOPLE.filter((p) => p.kind === "incoming");
  const person = readers.find((p) => p.id === s.reader) ?? readers[0];

  const view = useMemo(
    () => (latest ? viewFor(person, latest.claims, s.chunks) : null),
    [latest, person, s.chunks],
  );

  if (!latest || !view) {
    return (
      <Card className="p-8 text-center">
        <h3 className="text-lg font-semibold text-slate-900">No approved handover yet</h3>
        <p className="mt-1 text-sm text-slate-500">The reviewer must approve the handover before anyone can see it.</p>
        <div className="mt-4">
          <Button onClick={() => setStep(3)}>Go to Review</Button>
        </div>
      </Card>
    );
  }

  const visibleSources = [...new Set(s.chunks.filter((c) => view.visibleChunkIds.has(c.id) && c.kind !== "interview").map((c) => c.sourceName))];
  const hiddenSourceCount = new Set(s.chunks.filter((c) => !view.visibleChunkIds.has(c.id) && c.kind !== "interview").map((c) => c.sourceId)).size;
  const claims = dedupe(view.claims.filter((c) => !(c.type === "gap" && c.answeredBy)));
  const actions = nextActions(claims, CLUB.leaverName);
  const gaps = claims.filter((c) => c.type === "gap");
  const ack = s.acks.find((a) => a.personId === person.id && a.version === latest.version);

  function download() {
    const md = toMarkdown(person, latest.version, claims, chunkMap);
    const blob = new Blob([md], { type: "text/markdown" });
    const a = document.createElement("a");
    a.href = URL.createObjectURL(blob);
    a.download = `handover-${person.id}-v${latest.version}.md`;
    a.click();
    URL.revokeObjectURL(a.href);
  }

  const flagUi = (c: Claim) =>
    flagging === c.id ? (
      <div className="mt-2 flex gap-2">
        <input
          autoFocus
          value={reason}
          onChange={(e) => setReason(e.target.value)}
          placeholder="What is wrong?"
          className="flex-1 rounded-lg border border-slate-300 px-3 py-1.5 text-sm outline-none focus:border-teal-600"
        />
        <Button
          size="sm"
          disabled={!reason.trim()}
          onClick={() => {
            flag(c.id, person.id, reason.trim());
            setFlagging(null);
            setReason("");
          }}
        >
          Send to reviewer
        </Button>
        <Button size="sm" variant="ghost" onClick={() => setFlagging(null)}>
          Cancel
        </Button>
      </div>
    ) : null;

  const flagBtn = (c: Claim) =>
    s.flags.some((f) => f.claimId === c.id) ? (
      <span className="text-[11px] font-semibold text-amber-700">Flagged</span>
    ) : (
      <Button size="sm" variant="ghost" onClick={() => setFlagging(c.id)} title="Flag this claim as wrong">
        Flag
      </Button>
    );

  return (
    <div className="space-y-5">
      <Hint>
        Switch between the two incoming members to see that each gets a different handover, built only from sources they
        are allowed to see. Open any source, flag a wrong claim, and acknowledge receipt at the bottom.
      </Hint>

      <div className="flex flex-wrap gap-2">
        {readers.map((p) => (
          <button
            key={p.id}
            onClick={() => setReader(p.id)}
            className={cx(
              "rounded-xl border px-4 py-2 text-left",
              p.id === person.id ? "border-teal-700 bg-teal-700 text-white" : "border-slate-300 bg-white text-slate-800 hover:bg-slate-50",
            )}
          >
            <div className="text-sm font-semibold">{p.name}</div>
            <div className={cx("text-xs", p.id === person.id ? "text-teal-100" : "text-slate-500")}>{p.title}</div>
          </button>
        ))}
      </div>

      <Card className="overflow-hidden">
        <div className="bg-slate-900 px-5 py-4 text-white">
          <div className="text-xs uppercase tracking-wide text-teal-300">Handover · version {latest.version}</div>
          <h2 className="text-xl font-semibold">
            {person.name}, {person.title.toLowerCase()}
          </h2>
          <p className="text-sm text-slate-300">
            From {CLUB.leaverName} ({CLUB.leavingOn}) · approved by {latest.approvedBy} on {fmtDate(latest.approvedAt.slice(0, 10))}
          </p>
        </div>
        <div className="flex flex-wrap items-start gap-3 border-b border-slate-100 bg-violet-50 px-5 py-3 text-sm text-violet-950">
          <span className="text-lg leading-none">🔒</span>
          <div className="flex-1">
            Built only from the {visibleSources.length} sources {person.name.split(" ")[0]} can access:{" "}
            <span className="text-violet-800">{visibleSources.join(", ")}</span>. {hiddenSourceCount} other source(s) and{" "}
            <b>{view.withheld} claims</b> were excluded before this view was generated.
          </div>
        </div>
        <div className="grid grid-cols-2 gap-px bg-slate-100 sm:grid-cols-4">
          {[
            [claims.length, "claims in this handover"],
            [claims.filter((c) => c.status === "verified").length, "verified from sources"],
            [claims.filter((c) => c.status === "stated" || c.status === "inferred").length, "stated or inferred"],
            [gaps.length, "open gaps"],
          ].map(([n, l]) => (
            <div key={String(l)} className="bg-white px-4 py-3">
              <div className="text-xl font-semibold text-slate-900">{n}</div>
              <div className="text-xs text-slate-500">{l}</div>
            </div>
          ))}
        </div>
      </Card>

      <Card>
        <div className="border-b border-slate-100 px-4 py-3">
          <h3 className="font-semibold text-slate-900">Your first actions</h3>
          <p className="text-xs text-slate-500">Prioritised from your claims: work owned by the leaver, deadlines in the next 75 days, blockers and unowned tasks.</p>
        </div>
        <ol className="divide-y divide-slate-100">
          {actions.map((a, i) => (
            <li key={i} className="flex gap-3 px-4 py-3">
              <span className="flex h-6 w-6 shrink-0 items-center justify-center rounded-full bg-teal-700 text-xs font-semibold text-white">{i + 1}</span>
              <div>
                <div className="text-sm font-medium text-slate-900">{redact(a.text)}</div>
                <div className="text-xs text-slate-500">{a.why}</div>
              </div>
            </li>
          ))}
          {actions.length === 0 && <li className="px-4 py-3 text-sm text-slate-500">No urgent actions found.</li>}
        </ol>
      </Card>

      {SECTIONS.map((sec) => {
        const list = claims.filter((c) => sec.types.includes(c.type));
        if (!list.length) return null;
        return (
          <Card key={sec.title}>
            <div className="border-b border-slate-100 px-4 py-3">
              <h3 className="font-semibold text-slate-900">
                {sec.title} <span className="font-normal text-slate-400">({list.length})</span>
              </h3>
            </div>
            {list.map((c) => (
              <ClaimRow key={c.id} claim={c} chunkMap={chunkMap} right={flagBtn(c)}>
                {flagUi(c)}
              </ClaimRow>
            ))}
          </Card>
        );
      })}

      {gaps.length > 0 && (
        <Card className="border-slate-300">
          <div className="border-b border-slate-100 px-4 py-3">
            <h3 className="font-semibold text-slate-900">Open gaps ({gaps.length})</h3>
            <p className="text-xs text-slate-500">Nobody could answer these. Baton shows them instead of guessing.</p>
          </div>
          {gaps.map((c) => (
            <ClaimRow key={c.id} claim={c} chunkMap={chunkMap} right={flagBtn(c)}>
              {flagUi(c)}
            </ClaimRow>
          ))}
        </Card>
      )}

      <div className="flex flex-wrap items-center justify-between gap-3 rounded-xl bg-slate-900 px-5 py-4 text-white">
        <div className="text-sm">
          {ack ? (
            <>
              ✓ {person.name} acknowledged version {latest.version} on {new Date(ack.at).toLocaleString()}
            </>
          ) : (
            <>Confirm you have read this handover. The reviewer will see your acknowledgement.</>
          )}
        </div>
        <div className="flex gap-2">
          <Button variant="secondary" onClick={download}>
            Download (.md)
          </Button>
          <Button onClick={() => acknowledge(person.id)} disabled={Boolean(ack)}>
            {ack ? "Acknowledged" : "Acknowledge receipt"}
          </Button>
        </div>
      </div>
    </div>
  );
}
